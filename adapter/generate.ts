// Step 2 of the adapter: generate the directory `compile.ts` turns into the
// binary, `.next/next-compiler/`:
//
//   server.ts, require.ts, …   the runtime (`adapter/runtime/`), the entry
//   externals.ts               Next's `.external` modules, bundled once
//   next.config.json           the serialized config
//   app/                       the staged app (`stage.ts`, `native.ts`),
//                              embedded as files in `/$bunfs`
import {
  cpSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  rmSync,
  statSync,
  writeFileSync,
} from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { removeNativePackages, stageNativePackages } from "./native";
import { stageApp, type TracedAsset } from "./stage";

const DIST_DIR = "next-compiler";
const SERVER_RUNTIME = "runtime";
const SERVER_ENTRY_POINT = "server.ts";

const runtimeDir = join(
  dirname(fileURLToPath(import.meta.url)),
  SERVER_RUNTIME,
);

export type GenerateServerParams = {
  distDir: string;
  projectDir: string;
  repoRoot: string;
  assets: TracedAsset[];
  /** Packages with native addons, extracted to disk at runtime. */
  nativePackages: string[];
  /** Native packages the server never loads. Removed from the staged app. */
  excludedPackages: string[];
  /** Serialized Next config. The runtime reads it and does not load `next.config.ts`. */
  config: string;
};

export type GenerateServerResult = {
  serverEntryPoint: string;
};

export async function generateServer(
  params: GenerateServerParams,
): Promise<GenerateServerResult> {
  const serverDir = join(params.distDir, DIST_DIR);
  rmSync(serverDir, { recursive: true, force: true });
  // A copy of the runtime, not the original: it finds the staged app next to
  // itself (`import.meta.dir`), and `externals.ts` is overwritten below.
  cpSync(runtimeDir, serverDir, { recursive: true });

  const appDir = join(serverDir, "app");
  const { files } = stageApp(
    params.projectDir,
    params.repoRoot,
    appDir,
    params.assets,
  );
  console.log(`staged ${files} traced files at ${appDir}`);
  const removed = removeNativePackages(
    params.projectDir,
    appDir,
    params.excludedPackages,
  );
  if (removed.length) {
    console.log(`removed unused native packages: ${removed.join(", ")}`);
  }
  const native = stageNativePackages(
    params.projectDir,
    appDir,
    params.nativePackages,
  );
  if (native.packages.length) {
    console.log(`staged native packages: ${native.packages.join(", ")}`);
  }

  writeCacheHandlerShim(appDir);
  const externals = writeExternals(appDir, serverDir);
  console.log(`bundled ${externals} Next .external modules as single instances`);

  writeFileSync(join(serverDir, "next.config.json"), params.config);

  return { serverEntryPoint: join(serverDir, SERVER_ENTRY_POINT) };
}

// `next.config.cacheHandler` must be a module path, which Next loads with
// `import()`. This module re-exports the Redis handler compiled into the
// binary (`runtime/cache/index.ts` registers it and points the config here).
function writeCacheHandlerShim(appDir: string) {
  const dir = join(appDir, ".next-compiler");
  mkdirSync(dir, { recursive: true });
  writeFileSync(
    join(dir, "cache-handler.mjs"),
    'export default globalThis[Symbol.for("next-compiler.incremental-cache-handler")];\n',
  );
}

const EXTERNAL_REQUIRE = /require\("(next\/dist\/[^"]+\.external)(?:\.js)?"\)/g;

// Next marks with `.external` the modules that must be one instance shared by
// the server and the route bundles. Chunks and Next's compiled runtimes
// require them by name from `/$bunfs`, which would load a second copy. List
// every one the staged app requires, so the runtime bundles each once and
// hands that instance to every chunk (`runtime/externals.ts`).
//
// Each entry is a lazy `require()`: a static `require` makes Bun bundle the
// module, and the function defers running it until a chunk asks for it.
function writeExternals(appDir: string, serverDir: string): number {
  const specifiers = new Set<string>();
  const entries = readdirSync(appDir, { recursive: true, encoding: "utf8" });
  for (const entry of entries) {
    if (!entry.endsWith(".js")) continue;
    const path = join(appDir, entry);
    // Some packages name directories `*.js`.
    if (!statSync(path).isFile()) continue;
    const source = readFileSync(path, "utf8");
    for (const match of source.matchAll(EXTERNAL_REQUIRE)) {
      specifiers.add(match[1]);
    }
  }
  const lines = [...specifiers].sort().map((id) => {
    const name = JSON.stringify(id);
    return `  ${name}: () => require(${name}),`;
  });
  const source = [
    "// Generated by adapter/generate.ts.",
    "export const externals: Record<string, () => unknown> = {",
    ...lines,
    "};",
    "",
  ].join("\n");
  writeFileSync(join(serverDir, "externals.ts"), source);
  return specifiers.size;
}
