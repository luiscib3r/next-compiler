import {
  cpSync,
  readdirSync,
  readFileSync,
  rmSync,
  statSync,
  writeFileSync,
} from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { removeNativePackages, stageNativePackages } from "./native";
import { stageApp, type TracedAsset } from "./stage";

const DIST_DIR = "k8s-server";
const SERVER_RUNTIME = "runtime";
const SERVER_ENTRY_POINT = "server.ts";

const runtimeDir = join(
  dirname(fileURLToPath(import.meta.url)),
  SERVER_RUNTIME,
);

export type GenerateServerParams = {
  distDir: string;
  projectDir: string;
  repoRoot: string;
  assets: TracedAsset[];
  /** Packages with native addons, extracted to disk at runtime. */
  nativePackages: string[];
  /** Native packages the server never loads. Removed from the staged app. */
  excludedPackages: string[];
  /** Serialized Next config. The runtime reads it and does not load `next.config.ts`. */
  config: string;
};

export type GenerateServerResult = {
  serverEntryPoint: string;
};

export async function generateServer(
  params: GenerateServerParams,
): Promise<GenerateServerResult> {
  const serverDir = join(params.distDir, DIST_DIR);
  // Clean dist directory before generating server files
  rmSync(serverDir, { recursive: true, force: true });

  // Copy server runtime (folder) to dist directory
  cpSync(runtimeDir, serverDir, { recursive: true });

  const appDir = join(serverDir, "app");
  const { packages } = stageApp(
    params.projectDir,
    params.repoRoot,
    appDir,
    params.assets,
  );
  console.log(`staged ${packages} traced files at ${appDir}`);
  const removed = removeNativePackages(
    params.projectDir,
    appDir,
    params.excludedPackages,
  );
  if (removed.length) {
    console.log(`removed unused native packages: ${removed.join(", ")}`);
  }
  const native = stageNativePackages(
    params.projectDir,
    appDir,
    params.nativePackages,
  );
  if (native.packages.length) {
    console.log(`staged native packages: ${native.packages.join(", ")}`);
  }

  const externals = writeExternals(appDir, serverDir);
  console.log(`bundled ${externals} Next .external modules as single instances`);

  const serverEntryPoint = join(serverDir, SERVER_ENTRY_POINT);
  writeFileSync(join(serverDir, "next.config.json"), params.config);

  return { serverEntryPoint };
}

const EXTERNAL_REQUIRE = /require\("(next\/dist\/[^"]+\.external)(?:\.js)?"\)/g;

// Next marks with `.external` the modules that must be one instance shared by
// the server and the route bundles. Chunks and Next's compiled runtimes
// require them by name from `/$bunfs`, which would load a second copy. List
// every one the staged app requires, so the runtime bundles each once and
// hands that instance to every chunk (`runtime/externals.ts`).
function writeExternals(appDir: string, serverDir: string): number {
  const specifiers = new Set<string>();
  for (const entry of readdirSync(appDir, { recursive: true, encoding: "utf8" })) {
    if (!entry.endsWith(".js")) continue;
    const path = join(appDir, entry);
    // Some packages name directories `*.js`.
    if (!statSync(path).isFile()) continue;
    const source = readFileSync(path, "utf8");
    for (const match of source.matchAll(EXTERNAL_REQUIRE)) specifiers.add(match[1]);
  }
  const lines = [...specifiers]
    .sort()
    .map((id) => `  ${JSON.stringify(id)}: () => require(${JSON.stringify(id)}),`);
  writeFileSync(
    join(serverDir, "externals.ts"),
    `// Generated by adapter/generate.ts.\nexport const externals: Record<string, () => unknown> = {\n${lines.join("\n")}\n};\n`,
  );
  return specifiers.size;
}
